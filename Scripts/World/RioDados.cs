    static double[] _praia;
    public static double[] PRAIA
    {
        get
        {
            if (_praia == null)
            {
                double[] L = LITORAL;
                int n = L.Length / 2;
                _praia = new double[PRAIA_NOME.Length * 3];
                for (int k = 0; k < PRAIA_NOME.Length; k++)
                {
                    int[] idx = new int[2];
                    for (int e = 0; e < 2; e++)
                    {
                        double[] q = P(PRAIA_LL[k * 5 + e * 2], PRAIA_LL[k * 5 + e * 2 + 1]);
                        double mel = 1e18; int im = 0;
                        for (int i = 0; i < n; i++)
                        {
                            double dx = L[2 * i] - q[0], dz = L[2 * i + 1] - q[1];
                            double d = dx * dx + dz * dz;
                            if (d < mel) { mel = d; im = i; }
                        }
                        idx[e] = im;
                    }
                    _praia[k * 3] = System.Math.Min(idx[0], idx[1]);
                    _praia[k * 3 + 1] = System.Math.Max(idx[0], idx[1]);
                    _praia[k * 3 + 2] = PRAIA_LL[k * 5 + 4];
                }
            }
            return _praia;
        }
    }

