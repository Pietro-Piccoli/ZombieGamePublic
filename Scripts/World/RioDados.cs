    public static double[] P(double lat, double lon)
    { return new double[] { (lon - LON0) * M_LON, (lat - LAT0) * M_LAT }; }

    // ------------------------------------------------ helpers de forma
    static void Arco(List<double> o, double[] a, double[] b, double flecha, int n, double lado, bool pulaPrimeiro)
    {
        double dx = b[0] - a[0], dz = b[1] - a[1];
        double L = System.Math.Sqrt(dx * dx + dz * dz);
        double px = -dz / L * lado, pz = dx / L * lado;
        for (int i = pulaPrimeiro ? 1 : 0; i <= n; i++)
        {
            double t = i / (double)n;
            double s = System.Math.Sin(System.Math.PI * t) * flecha;
            o.Add(a[0] + dx * t + px * s);
            o.Add(a[1] + dz * t + pz * s);
        }
    }

    static void Pt(List<double> o, double lat, double lon)
    { double[] q = P(lat, lon); o.Add(q[0]); o.Add(q[1]); }

    static double[] Densificar(List<double> pts, double passo)
    {
        var o = new List<double>();
        o.Add(pts[0]); o.Add(pts[1]);
        for (int i = 0; i + 3 < pts.Count; i += 2)
        {
            double ax = pts[i], az = pts[i + 1], bx = pts[i + 2], bz = pts[i + 3];
            double L = System.Math.Sqrt((bx - ax) * (bx - ax) + (bz - az) * (bz - az));
            int n = (int)System.Math.Ceiling(L / passo); if (n < 1) n = 1;
            for (int k = 1; k <= n; k++)
            {
                double t = k / (double)n;
                o.Add(ax + (bx - ax) * t); o.Add(az + (bz - az) * t);
            }
        }
        return o.ToArray();
    }

    static double[] Rugosidade(double[] pts, double amp, double semente)
    {
        double esc = 0.0021;
        int n = pts.Length / 2;
        double[] o = new double[pts.Length];
        for (int i = 0; i < n; i++)
        {
            int ia = i > 0 ? i - 1 : 0, ib = i < n - 1 ? i + 1 : n - 1;
            double dx = pts[2 * ib] - pts[2 * ia], dz = pts[2 * ib + 1] - pts[2 * ia + 1];
            double L = System.Math.Sqrt(dx * dx + dz * dz); if (L < 1e-9) L = 1.0;
            double nx = -dz / L, nz = dx / L;
            double x = pts[2 * i], z = pts[2 * i + 1];
            double r = System.Math.Sin(x * esc + semente) * 0.6
                     + System.Math.Sin(z * esc * 1.7 - semente * 1.3) * 0.4
                     + System.Math.Sin((x + z) * esc * 3.1 + semente * 2.7) * 0.25;
            o[2 * i] = x + nx * r * amp;
            o[2 * i + 1] = z + nz * r * amp;
        }
        return o;
    }

